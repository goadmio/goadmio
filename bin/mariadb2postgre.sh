#!/bin/bash

echo "$(date +"[%b %d %H:%M:%S]#") $(basename "$0") $@" | sudo tee -a "/var/log/go/$(basename "$0").log" >/dev/null

File=$1

# mariadb-dump mls > $File

sudo sed -i -E '/^\/\*/d' $File
sudo sed -i -E '/^--/d' $File
sudo sed -i -E '/^LOCK TABLES/d' $File
sudo sed -i -E '/^UNLOCK TABLES/d' $File
sudo sed -i -E '/^set autocommit/Id' $File
sudo sed -i -E '/^commit;/Id' $File
sudo sed -i 's/AUTO_INCREMENT/GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/gi' $File
sudo sed -i 's/char(0)/char(255)/gi' $File
sudo sed -i 's/0000-00-00/2000-01-01/gi' $File
sudo sed -i 's/ varchar(/ character varying(/gi' $File
sudo sed -i 's/ char(/ character(/gi' $File
sudo sed -i -E 's/ tinyint\([0-9]+\) / smallint /gi' $File
sudo sed -i -E 's/ bigint\([0-9]+\) / bigint /gi' $File
sudo sed -i -E 's/ int\([0-9]+\) / integer /gi' $File
sudo sed -i -E 's/ mediumint\([0-9]+\) / integer /gi' $File
sudo sed -i 's/ mediumtext / text /gi' $File
sudo sed -i 's/ DOUBLE / DOUBLE PRECISION /gi' $File
sudo sed -i 's/ DATETIME / TIMESTAMP /gi' $File
sudo sed -i 's/ bigint\([0-9]+\) / bigint /gi' $File
sudo sed -i 's/ unsigned / /gi' $File
sudo sed -i 's/`//g' $File
sudo sed -i -E 's/ ENGINE=[A-Za-z_]+[^;]*;/;/g' $File
sudo sed -i -E '/ KEY [A-Za-z0-9_]+ \(/d' $File
sudo sed -i -E '/ PRIMARY KEY \(/d' $File
sudo sed -i -E '/ UNIQUE KEY /d' $File

sudo sed -i 's/EXISTS User;/EXISTS Users;/gi' $File
sudo sed -i 's/CREATE TABLE User /CREATE TABLE Users /gi' $File
sudo sed -i 's/INSERT INTO User VALUES/INSERT INTO Users VALUES/gi' $File

sudo sed -i "s/\\\'/''/g" $File
sudo sed -i 's/\\u[0-9a-fA-F]\{4\}//g' $File
sudo sed -i 's/\\//g' $File
sudo sed -i 's/\\//g' $File
perl -i -0777 -pe 's/,\n\);/);/g' $File

