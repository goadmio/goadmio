#!/bin/bash

echo "$(date +"[%b %d %H:%M:%S]#") $(basename "$0") $@" | sudo tee -a "/var/log/go/$(basename "$0").log" >/dev/null

source /go/function
LOG=$(LOG)

LockFile="/usr/local/goadmio/lock/block.lock"
if [ "$1" = "block" ]; then

    if sudo test -f $LockFile ; then
        if [[ $(($(date +%s) - $(stat -c %Y $LockFile 2>/dev/null))) -le "60" ]]; then
            InstanceFile=$(<$LockFile)
            echo "Instance ($InstanceFile) already running."
            exit 1
        fi
    fi

    echo "$(basename "$0")" | sudo tee "$LockFile" >/dev/null

	# Run When Click Ctrl+C
	trap 'sudo rm -f "$LockFile"' EXIT

fi

Stamp=$1

TimeStamp=$(date +'%s')
TTL=$((TimeStamp - 3600))

Hostname=$(</etc/hostname)
IPv4=$(curl -s -4 checkip.amazonaws.com)
IPv6=$(curl -s -6 https://icanhazip.com)

WS=$(</usr/local/goadmio/linux/ws.db)
OS=$(</usr/local/goadmio/linux/os.db)

if sudo test -f "/var/go/etc/404top" ; then

    Limit=$(</var/go/etc/404top)

    if ! [[ "$Limit" =~ ^[0-9]+$ ]]; then
        Limit="300"
    fi

else

    Limit="300"

fi

Code=$(sudo grep ' 404 ' $LOG | awk -F'|' -v TTL="$TTL" '$6 > TTL { if ($4 != "-") print $4; else print $3 }' | sort | uniq -ci | sort -nr | head -25)

Visits=$(echo "$Code" | awk '{print $1}')
Visits=$(echo $Visits | tr "\n" " ")
IFS=' ' read -r -a VisitsArray <<<"$Visits"

IPArray=$(echo "$Code" | awk '{print $2'})

OUTPUT="IP|VISITS|COUNTRY|CITY|COMPANY"
OUTPUT="$OUTPUT\n--|------|-------|----|-------"

N=0
E=0
for IP in $IPArray; do

    echo "$(basename "$0")" | sudo tee "$LockFile" >/dev/null
    Visits="${VisitsArray[$N]}"

    if [ "$IP" != "$IPv4" ] && [ "$IP" != "$IPv6" ] && [ "$IP" != "127.0.0.1" ]; then

        Whois=$(WHOIS "$IP")
        Company=$(COMPANY "$Whois" "$IP")

        if [ -t 0 ]; then
            Country=$(COUNTRY "$IP")
            City=$(CITY "$IP")
        else
            Country=$(echo "$Whois" | awk 'tolower($1) == "country:" { print $2;exit }')
            City=$(echo "$Whois" | grep -i "city:" | head -n1 | awk -F: '{print $2}' | sed 's/^[ \t]*//')
        fi

        if [[ "${Company,,}" != *"google"* ]] && [[ "$Company" != *"bing"* ]] && [[ "$Company" != *"cloudflare"* ]]; then

            if [ "$Stamp" = "block" ]; then

                if [[ "$Visits" -ge "$Limit" ]]; then

                    if ! compgen -G "/var/log/go/block/$IP.*" >/dev/null; then

                        E=$(($E + 1))
                        Err="${Err}- 404 Block $IP ($Visits Visits) - Country: $Country, Company: $Company.\n\n"

                        sudo /go/block $IP 404 "$Country" "$Company"

                    fi

                fi

            fi

        fi

        OUTPUT="$OUTPUT\n$IP|$Visits|$Country|$City|$Company"

    fi

    N=$(($N + 1))

done

echo -ne $OUTPUT | column -t -s "|"

if [ "$E" -gt "0" ]; then

    Header="Dear Server Administrator,\n\nThis is an automated security notification from the GoAdmio AI System.\n\nOur AI-powered monitoring tool has identified and automatically blocked IP addresses generating an unusually high volume of 404 (Page Not Found) errors. This pattern typically indicates scanning attempts, vulnerability probes, or malicious content discovery activity targeting your server. These blocks are designed to prevent information leakage and protect against potential attacks.\n\nBelow is the list of IP addresses that have been temporarily or permanently blocked due to excessive 404 error patterns:\n\nBlocked IPs Due to High 404 Activity:\n"
    Footer="The GoAdmio AI System will continue to monitor traffic in real time and apply intelligent rate-limiting and blocking to safeguard your server resources.\n\nFor further details or to adjust blocking rules, please visit your GoAdmio dashboard or contact our support team.\n\nStay secure,\nGoAdmio AI Traffic Management Team\nwww.goadmio.com\n\n"
    Note="Note: This email is automatically generated by the GoAdmio AI System. Please do not reply directly to this message.\n\n"

    sudo /go/sendmail "High 404 errors detected ($E IPs)" "${Header}${Err}${Footer}${Note}" "Block"
    sudo /go/sendwhatsapp "*High 404 errors detected ($E IPs)*\n\n${Header}${Err}${Footer}${Note}" "Block"

fi

sudo rm -f $LockFile
