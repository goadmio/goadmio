#!/bin/bash

echo "$(date +"[%b %d %H:%M:%S]#") $(basename "$0") $@" | sudo tee -a "/var/log/go/$(basename "$0").log" >/dev/null

source /go/function
LOG=$(LOG)

LockFile="/usr/local/goadmio/lock/block.lock"
if [ "$1" = "block" ] || [ "$1" = "underattack" ]; then

    if sudo test -f $LockFile ; then
        if [[ $(($(date +%s) - $(stat -c %Y $LockFile 2>/dev/null))) -le "60" ]]; then
            InstanceFile=$(<$LockFile)
            echo "Instance ($InstanceFile) already running."
            exit 1
        fi
    fi

    echo "$(basename "$0")" | sudo tee "$LockFile" >/dev/null

	# Run When Click Ctrl+C
	trap 'sudo rm -f "$LockFile"' EXIT

fi

Stamp=$1
TimeStamp=$(date +'%s')
Hostname=$(</etc/hostname)
IPv4=$(curl -s -4 checkip.amazonaws.com)
IPv6=$(curl -s -6 https://icanhazip.com)

OUTPUT="IP|VISITS|COUNTRY|CITY|COMPANY"
OUTPUT="$OUTPUT\n--|------|-------|----|-------"

Head=20

Limit=100

N=0
E=0

Code=$(sudo grep "Failed password" /var/log/secure | awk '{print $(NF-3)}' | sort | uniq -c | sort -nr | head -$Head)

Visits=$(echo "$Code" | awk '{print $1'})
Visits=$(echo $Visits | tr "\n" " ")
IFS=' ' read -r -a VisitsArray <<<"$Visits"

IPArray=$(echo "$Code" | awk '{print $2'})

for IP in $IPArray; do

    echo "$(basename "$0")" | sudo tee "$LockFile" >/dev/null
    Visits="${VisitsArray[$N]}"

    if [ "$IP" != "$IPv4" ] && [ "$IP" != "$IPv6" ] && [ "$IP" != "127.0.0.1" ]; then

        Whois=$(WHOIS "$IP")
        Company=$(COMPANY "$Whois" "$IP")

        if [ -t 0 ]; then
            Country=$(COUNTRY "$IP")
            City=$(CITY "$IP")
        else
            Country=$(echo "$Whois" | awk 'tolower($1) == "country:" { print $2;exit }')
            City=$(echo "$Whois" | grep -i "city:" | head -n1 | awk -F: '{print $2}' | sed 's/^[ \t]*//')
        fi

        if [[ "${Company,,}" != *"google"* ]] && [[ "$Company" != *"bing"* ]] && [[ "$Company" != *"cloudflare"* ]]; then

            if [ "$Stamp" = "block" ]; then

                if [[ "$Visits" -ge "$Limit" ]]; then

                    if ! compgen -G "/var/log/go/block/$IP.*" >/dev/null; then

                        E=$(($E + 1))
                        Err="${Err}- SSH Brute Force Attacks $IP ($Visits Visits) - Country: $Country, Company: $Company.\n\n"

                        sudo /go/block $IP ssh "$Country" "$Company"

                    fi

                fi

            fi

        fi

        OUTPUT="$OUTPUT\n$IP|$Visits|$Country|$City|$Company"

    fi

    N=$(($N + 1))

done

echo -ne $OUTPUT | column -t -s "|"

if [ "$E" -gt "0" ]; then

    Header="Dear Server Administrator,\n\nThis is an automated security alert from GoAdmio AI.\n\nMultiple failed SSH login attempts were detected on your server, indicating a potential brute force attack. The system has automatically blocked the IP addresses responsible for these repeated authentication failures.\n\nThis measure prevents unauthorized access attempts and protects your server from compromise.\n\nBlocked IP Addresses:\n"
    Footer="The GoAdmio AI System will continue to monitor SSH authentication logs and block malicious IPs in real-time. Should you have any questions or require further details regarding these blocked IPs, please do not hesitate to reach out.\n\nThank you for ensuring the security and integrity of your server.\n\nBest regards,\nGoAdmio AI Security Team\nwww.goadmio.com\n\n"
    Note="Note: This email is automatically generated by the GoAdmio AI System. Please do not reply directly to this message."

    sudo /go/sendmail "Blocking SSH Brute Force Attacks ($E IPs)" "${Header}${Err}${Footer}${Note}" "Block"
    sudo /go/sendwhatsapp "*Blocking SSH Brute Force Attacks ($E IPs)*\n\n${Header}${Err}${Footer}${Note}" "Block"

fi

sudo rm -f $LockFile
