#!/bin/bash

echo "$(date +"[%b %d %H:%M:%S]#") $(basename "$0") $@" | sudo tee -a "/var/log/go/$(basename "$0").log" >/dev/null

TimeStamp=$(date +'%s')

Send=0

sudo mkdir -p /usr/local/goadmio/db/shell

# PHP Shell Scanner

Dir=$(sudo find /home/*/www -type f -name "*.php" -mmin -1440 -exec grep -ioE "(base64_decode|proc_open|shell_exec|exec\(|exec \(|system\(|system \(|passthru)" /dev/null {} \; | head -25)
Dir=$(echo "$Dir" | sed 's/(//g')

if [[ "$Dir" = *"/"* ]]; then

    echo "$Dir"

    while IFS= read -r Line; do

        File=$(echo -n "$Line" | md5sum | awk '{print $1}')

        if sudo test ! -f "/usr/local/goadmio/db/shell/$File" ; then

            echo "" | sudo tee /usr/local/goadmio/db/shell/$File >/dev/null

            Send=1

            Err="${Err}$Line\n\n"

        fi

    done <<<"$Dir"

    if [ "$Send" -eq "1" ]; then

        Header="Dear Server Administrator,\n\nThis is an automated security notification from the GoAdmio AI System.\n\nOur advanced AI-powered monitoring tool has detected potentially malicious PHP shell scripts on your server. These scripts could be used by attackers to gain unauthorized access, execute commands, or maintain persistence on your system. The detection was based on analysis of file signatures, behavioral patterns, and known malware characteristics.\n\nBelow is the list of suspicious PHP files that may pose a security risk:\n\nDetected PHP Shell Scripts:\n"
        Footer="The GoAdmio AI System will continue to monitor and protect your server in real-time. Should you have any questions, need assistance with file verification, or require further details regarding these detections, please do not hesitate to reach out.\n\nThank you for ensuring the security and integrity of your server.\n\nBest regards,\nGoAdmio AI Security Team\nwww.goadmio.com\n\n"
        Note="Note: This email is automatically generated by the GoAdmio AI System. Please do not reply directly to this message.\n\n"

        sudo /go/sendmail "Security Alert: PHP Shell Scripts Detected on Your Server" "${Header}${Err}${Footer}${Note}" "Security"
        sudo /go/sendwhatsapp "*Security Alert: PHP Shell Scripts Detected on Your Server*\n\n${Header}${Err}${Footer}${Note}" "Security"

    else

        echo "There are no new PHP shell files."

    fi

fi

if sudo test -f /var/go/etc/go.key ; then

    MAC=$(sudo /usr/sbin/ifconfig | awk '/ether/ {print $2}' | base64)
    RemotePassword=$(sudo openssl base64 -d -aes-128-cbc -d -pbkdf2 -nosalt -md md5 -in /var/go/etc/go.key -pass pass:"$MAC")

    Dir=$(sudo find /home/*/www -type f -name "*.php" -mmin -1440 -exec grep -ioE "($RemotePassword)" /dev/null {} \; | head -25)

    if [[ "$Dir" = *"/"* ]]; then

        Replacement=$(printf '*%.0s' $(seq 1 ${#RemotePassword}))
        Dir=$(echo "${Dir//$RemotePassword/$Replacement}")

        echo "$Dir"

        sudo /go/sendmail "ROOT Password Scanner" "$Dir" "Security"
        sudo /go/sendwhatsapp "*ROOT Password Scanner*\n\n$Dir" "Security"

    fi

fi
