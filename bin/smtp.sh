#!/bin/bash

echo "$(date +"[%b %d %H:%M:%S]#") $(basename "$0") $@" | sudo tee -a "/var/log/go/$(basename "$0").log" >/dev/null

MySQLRootPassword=$(sudo grep -oP 'DBPass="\K[^"]+' /usr/local/goadmio/include/config/config.php)

WS=$(</usr/local/goadmio/linux/ws.db)
OS=$(</usr/local/goadmio/linux/os.db)
Hostname=$(</etc/hostname)
ServerIP=$(curl -s -4 checkip.amazonaws.com)

if [ "$1" = "block" ]; then

    Header="Dear Server Administrator,\n\nThis is an automated security alert from GoAdmio AI Outbound Protection.\n\nOur system has detected a high volume of identical outgoing messages from your server (SMTP port 25), consistent with spam or a compromised account. To protect your server's reputation and prevent abuse, outbound SMTP access has been automatically restricted for the affected source(s).\n\n"
    Footer="This action only blocks external mail via port 25. Internal mail flow and other services remain unaffected.\n\nGoAdmio AI continuously monitors outbound SMTP for anomalies. To review logs, affected accounts, manage whitelists, or adjust sensitivity, run /go/mailtop or visit your GoAdmio dashboard.\n\nTo unblock port 25, run: /go/smtp unblock\n\nStay secure,\nGoAdmio AI Security Team\nwww.goadmio.com\n\n"
    Note="Note: This email is automatically generated by the GoAdmio AI System. Please do not reply directly to this message.\n\n"

    sudo /go/sendmail "Automated Action: Outbound Port 25 (SMTP) Blocked to Prevent Spam" "${Header}${Err}${Footer}${Note}" "Outbound SPAM"
    sudo /go/sendwhatsapp "*Automated Action: Outbound Port 25 (SMTP) Blocked to Prevent Spam*\n\n${Header}${Err}${Footer}${Note}" "Outbound SPAM"

    sleep 5

    if [[ "$OS" = @(AlmaLinux|Rocky|CentOS|Red Hat|Fedora) ]]; then

        sudo firewall-cmd --permanent --direct --add-rule ipv4 filter OUTPUT 0 -p tcp --dport 25 -j DROP
        sudo firewall-cmd --permanent --direct --add-rule ipv6 filter OUTPUT 0 -p tcp --dport 25 -j DROP
        sudo firewall-cmd --reload >/dev/null 2>&1

    elif [[ "$OS" = @(Debian|Ubuntu) ]]; then

        sudo ufw deny out 25

    fi

    sudo /go/welcome

    echo "Port 25 is closed"

    exit 1

fi

if [ "$1" = "unblock" ]; then

    if [[ "$OS" = @(AlmaLinux|Rocky|CentOS|Red Hat|Fedora) ]]; then

        sudo firewall-cmd --permanent --direct --remove-rule ipv4 filter OUTPUT 0 -p tcp --dport 25 -j DROP
        sudo firewall-cmd --permanent --direct --remove-rule ipv6 filter OUTPUT 0 -p tcp --dport 25 -j DROP
        sudo firewall-cmd --reload >/dev/null 2>&1

    elif [[ "$OS" = @(Debian|Ubuntu) ]]; then

        sudo ufw delete deny out 25

    fi

    sudo /go/welcome

    echo "Port 25 is opened"

    exit 1
fi

if [ "$1" = "enable" ] || [ "$1" = "26" ]; then

    # Enable SMTP PORT 26
    sudo sed -i "/^26 .*/d" /etc/postfix/master.cf
    echo "26        inet  n       -       n       -       -       smtpd" | sudo tee -a /etc/postfix/master.cf >/dev/null
    sudo sqlite3 -batch -init /root/.sqliterc /var/lib/sqlite/config.db "UPDATE Config set PostfixSMTPPort='26' where ConfigID=1"

else

    sudo sed -i "s/^26 .*//g" /etc/postfix/master.cf
    sudo sqlite3 -batch -init /root/.sqliterc /var/lib/sqlite/config.db "UPDATE Config set PostfixSMTPPort='25' where ConfigID=1"

fi

sudo systemctl restart postfix
