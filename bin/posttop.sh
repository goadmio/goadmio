#!/bin/bash

echo "$(date +"[%b %d %H:%M:%S]#") $(basename "$0") $@" | sudo tee -a "/var/log/go/$(basename "$0").log" >/dev/null

source /go/function
LOG=$(LOG)

LockFile="/usr/local/goadmio/lock/block.lock"
if [ "$1" = "block" ]; then

    if sudo test -f $LockFile ; then
        if [[ $(($(date +%s) - $(stat -c %Y $LockFile 2>/dev/null))) -le "60" ]]; then
            InstanceFile=$(<$LockFile)
            echo "Instance ($InstanceFile) already running."
            exit 1
        fi
    fi

    echo "$(basename "$0")" | sudo tee "$LockFile" >/dev/null

	# Run When Click Ctrl+C
	trap 'sudo rm -f "$LockFile"' EXIT

fi

Stamp=$1
TimeStamp=$(date +'%s')

if [[ "$Stamp" =~ ^[0-9]+$ ]]; then
    TTL=$((TimeStamp - $Stamp))
elif [ "$Stamp" = "block" ]; then
    TTL=$((TimeStamp - 3600))
else
    TTL=$((TimeStamp - 86400))
fi

if sudo test -f "/var/go/etc/posttop" ; then

    Limit=$(</var/go/etc/posttop)

    if ! [[ "$Limit" =~ ^[0-9]+$ ]]; then
        Limit="300"
    fi

else

    Limit="300"

fi

WS=$(</usr/local/goadmio/linux/ws.db)
OS=$(</usr/local/goadmio/linux/os.db)
IPv4=$(curl -s -4 checkip.amazonaws.com)
IPv6=$(curl -s -6 https://icanhazip.com)

Code=$(sudo grep "|POST" $LOG | awk -F'|' '{ if ($6 > '"$TTL"' && $4 != "-") print $4; else if ($6 > '"$TTL"') print $3 }' | sort | uniq -ci | sort -nr | head -20)

Visits=$(echo "$Code" | awk '{print $1}')
Visits=$(echo $Visits | tr "\n" " ")
IFS=' ' read -r -a VisitsArray <<<"$Visits"

IPArray=$(echo "$Code" | awk '{print $2'})

OUTPUT="IP|VISITS|COUNTRY|CITY|COMPANY"
OUTPUT="$OUTPUT\n--|------|-------|----|-------"

N=0
for IP in $IPArray; do

    echo "$(basename "$0")" | sudo tee "$LockFile" >/dev/null
    Visits="${VisitsArray[$N]}"

    if [ "$IP" != "$IPv4" ] && [ "$IP" != "$IPv6" ] && [ "$IP" != "127.0.0.1" ]; then

        Whois=$(WHOIS "$IP")
        Company=$(COMPANY "$Whois" "$IP")

        if [ -t 0 ]; then
            Country=$(COUNTRY "$IP")
            City=$(CITY "$IP")
        else
            Country=$(echo "$Whois" | awk 'tolower($1) == "country:" { print $2;exit }')
            City=$(echo "$Whois" | grep -i "city:" | head -n1 | awk -F: '{print $2}' | sed 's/^[ \t]*//')
        fi

        if [[ "${Company,,}" != *"google"* ]] && [[ "$Company" != *"bing"* ]] && [[ "$Company" != *"cloudflare"* ]]; then

            if [ "$Stamp" = "block" ]; then

                if [[ "$Visits" -ge "$Limit" ]]; then

                    if ! compgen -G "/var/log/go/block/$IP.*" >/dev/null; then

                        E=$(($E + 1))
                        Err="${Err}- POST Traffic $IP ($Visits Visits / Hour) - Country: $Country, Company: $Company.\n\n"

                        sudo /go/block $IP post "$Country" "$Company"

                    fi

                fi

            fi

        fi

        OUTPUT="$OUTPUT\n$IP|$Visits|$Country|$City|$Company"

    fi

    N=$(($N + 1))

done

echo -ne $OUTPUT | column -t -s "|"

if [ "$E" -gt "0" ]; then

    Header="Dear Server Administrator,\n\nGoAdmio's AI security system has automatically blocked IP addresses generating abnormally high volumes of POST requests to your server, indicating potential application-layer attack patterns.\n\nBlocked IPs:\n"
    Footer="This protection prevents resource exhaustion and maintains your application's availability. Legitimate API clients may need whitelisting via your dashboard.\n\nBest regards,\nGoAdmio AI Security Team\nwww.goadmio.com\n\n"
    Note="Note: This email is automatically generated by the GoAdmio AI System. Please do not reply directly to this message.\n\n"

    sudo /go/sendmail "Automated Block: Excessive POST Requests Detected ($E IPs)" "${Header}${Err}${Footer}${Note}" "Block"
    sudo /go/sendwhatsapp "*Automated Block: Excessive POST Requests Detected ($E IPs)*\n\n${Header}${Err}${Footer}${Note}" "Block"

fi

sudo rm -f $LockFile
